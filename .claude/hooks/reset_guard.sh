#!/usr/bin/env bash
# 利用者が発話したら自走の状態をリセットする(UserPromptSubmit / SessionStart)。
#
# 1. 自走カウンタを消す。
# 2. 裁定待ち札を消す(裁定は発話で解決したとみなす)。
# 3. **停止札も消す** — 一度置いたら二度と作業再開できない、を防ぐ。
#
# **発話から停止の意思を推測することはしない(2026-08-14 に撤去)。**
# 言葉尻を検知する仕組みは、黙って効かないときに気づけず、利用者に
# 「魔法の言葉」を強いる。しかも試験のために AI が偽の利用者発話を
# 作文することになり、それが会話へ紛れ込む温床になった(実際に起きた)。
# 停止は明示の操作で行う: .claude/停止 を置く、/hooks で切る、Esc。
#
# 詳細は stop_guard.sh のコメントと docs/教訓.md §11。

set -u

root="${CLAUDE_PROJECT_DIR:-e:/WORKSPACE/ExoClim-3}"
d="$root/.claude"

rm -f "$d/.自走カウンタ" "$d/裁定待ち.md" "$d/停止" 2>/dev/null
exit 0
