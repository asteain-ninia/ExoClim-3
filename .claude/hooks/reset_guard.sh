#!/usr/bin/env bash
# 利用者が発話したら自走の状態をリセットする(UserPromptSubmit / SessionStart)。
#
# 1. 自走カウンタと裁定待ち札を消す(裁定は利用者の発話で解決したとみなす)。
# 2. **停止札も消す** — 一度置いたら二度と作業再開できない、を防ぐ。
# 3. そのうえで、発話が**停止の意思**を表しているなら停止札を置き直す。
#    語彙は実際のセッションログから採った(「PC使いたいです」「また24時に
#    お返し予定です」「24時以降は寝てます」など)。利用者が機械を空けたい
#    と言っているのに自走を強制するのは、フックの目的の真逆になる。
#
# 詳細は stop_guard.sh のコメントと docs/教訓.md §11。

set -u

root="${CLAUDE_PROJECT_DIR:-e:/WORKSPACE/ExoClim-3}"
d="$root/.claude"

payload=$(cat 2>/dev/null || true)

rm -f "$d/.自走カウンタ" "$d/裁定待ち.md" "$d/停止" 2>/dev/null

# 停止の意思を表す語。**作業の依頼と紛れないもの**だけを選ぶ。
# 「状況?」「どう?」のような様子見は停止ではない(答えたあと作業へ戻る)。
case "$payload" in
  *止めて* | *とめて* | *ストップ* | *中断* | *停止して* | \
  *PC使い* | *ＰＣ使い* | *パソコン使い* | *GPU使い* | *グラボ使い* | \
  *寝ます* | *寝る* | *おやすみ* | *お休みします* | \
  *今日はここまで* | *終わりに* | *終了して* | *休憩*)
    printf '利用者の発話に停止の意思を検出したため自動で置いた\n' > "$d/停止"
    printf '{"systemMessage":"停止の意思を検出したので自走フックを解除しました(次の指示で自動的に戻ります)"}\n'
    ;;
esac

exit 0
